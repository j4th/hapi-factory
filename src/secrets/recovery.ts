/**
 * The recovery (break-glass) identity and its 10 words (spec §11.5).
 *
 * Every store is also encrypted to a recovery recipient. Its identity is made
 * in memory (`newIdentity`: age-keygen -pq, its recipient read back with
 * `age-keygen -y` on stdin, since `-y` can't read a wrapped file later), then
 * wrapped with a passphrase of 10 words (`wrapIdentity`) and written as
 * recovery.age beside the store. The wrapped file is useless without the
 * words, so it may sit in private/ and be backed up with the store. The
 * user's one backup job is the words.
 *
 * - **The words** are drawn by hapi, with crypto.getRandomValues, from the
 *   2048-word list age itself uses for `age -p` (./wordlist.ts): 10 words,
 *   110 bits, behind age's scrypt. (`age -p` can generate words too, but
 *   prints them only to /dev/tty, so hapi couldn't confirm the user kept
 *   them.) The passphrase is the words joined by "-", like age's own, so
 *   `age -d -i recovery.age` opens the file by hand too.
 * - **Wrapping** is non-interactive: `age -e -a -j batchpass` with
 *   AGE_PASSPHRASE_FD=3 and the passphrase piped on fd 3 (the
 *   age-plugin-batchpass interface, age >= 1.3). The plaintext identity goes
 *   on stdin. Neither it nor the words ever reach argv, env or a file.
 * - **The terminal** (`openTerminal`): the words are shown on /dev/tty, never
 *   stdout or stderr (which a log or pipe could keep), and read back from it
 *   with echo off where the terminal allows.
 */
import { closeSync, openSync, writeSync } from "node:fs";
import { SecretError } from "./provider";
import { commandRunner, type SopsRunner, scrubToolError } from "./providers/sops";
import { kindName, recipientType, shortRecipient } from "./recipients";
import { WORDLIST } from "./wordlist";

/** How many words the passphrase has: 10 x 11 bits = 110 bits. */
export const WORD_COUNT = 10;

const WORDS = new Set(WORDLIST);

/**
 * `WORD_COUNT` words from the list, each from one uint16 of `random`
 * (crypto.getRandomValues by default) taken mod 2048: uniform, since 65536 is
 * a multiple of 2048.
 */
export function generateWords(random: (a: Uint16Array) => Uint16Array = (a) => crypto.getRandomValues(a)): string[] {
  const values = random(new Uint16Array(WORD_COUNT));
  return [...values].map((v) => WORDLIST[v % WORDLIST.length]!);
}

/** The passphrase age is given: the words joined by "-", as in age's own autogenerated passphrases. */
export function passphraseOf(words: readonly string[]): string {
  return words.join("-");
}

/**
 * The words as typed: split on whitespace or "-", lower-cased. Throws a
 * SecretError naming the position of a word that isn't in the list, or the
 * count if it isn't `WORD_COUNT`. Never echoes a word.
 */
export function parseWords(input: string): string[] {
  const words = input
    .toLowerCase()
    .split(/[\s-]+/)
    .filter((w) => w !== "");
  if (words.length !== WORD_COUNT) throw new SecretError(`expected ${WORD_COUNT} words, got ${words.length}`);
  const bad = words.findIndex((w) => !WORDS.has(w));
  if (bad !== -1) throw new SecretError(`word ${bad + 1} is not in the list (check its spelling)`);
  return words;
}

/** Where the words are shown and typed: the user's terminal, never stdout or stderr. */
export interface Tty {
  write(text: string): void;
  /** Show `prompt`, then read one line, with echo off where the terminal allows. */
  read(prompt: string): Promise<string>;
}

/**
 * Read one line from /dev/tty with echo off, in a shell that restores echo
 * however it ends (Ctrl-C included), and print the line on stdout: a pipe to
 * hapi, never a file.
 */
const READ_LINE = [
  "exec 0</dev/tty || exit 3",
  "trap 'stty echo 2>/dev/null; exit 130' INT TERM HUP",
  "stty -echo 2>/dev/null",
  "IFS= read -r line; s=$?",
  "stty echo 2>/dev/null",
  "printf '\\n' >/dev/tty",
  "printf '%s' \"$line\"",
  "exit $s",
].join("\n");

/** The user's terminal, /dev/tty, or undefined if there is none (no controlling terminal: CI, a service). */
export function openTerminal(path = "/dev/tty"): Tty | undefined {
  let fd: number;
  try {
    fd = openSync(path, "w");
  } catch {
    return undefined;
  }
  process.once("exit", () => {
    try {
      closeSync(fd);
    } catch {}
  });
  const sh = commandRunner("/bin/sh");
  return {
    write: (text) => void writeSync(fd, text),
    async read(prompt) {
      writeSync(fd, prompt);
      const r = await sh(["-c", READ_LINE], { env: { PATH: "/usr/bin:/bin" } });
      if (r.code === 130) throw new SecretError("cancelled");
      if (r.code !== 0) throw new SecretError(`could not read from the terminal (exit ${r.code})`);
      return r.stdout;
    },
  };
}

/** Whether a person may be at the terminal: stdin is one, or the process has a controlling terminal. */
export function attendedTerminal(): boolean {
  if (process.stdin.isTTY === true) return true;
  try {
    closeSync(openSync("/dev/tty", "r"));
    return true;
  } catch {
    return false;
  }
}

/** Clear the screen and its scrollback, and go home. */
const CLEAR = "\x1b[2J\x1b[3J\x1b[H";

const KEEP_THEM =
  "Store these 10 words where you keep things you can't lose (a password manager, paper in a safe, or both). With recovery.age they open your secrets if every machine is lost.";

function wordsBlock(words: readonly string[]): string {
  const cell = (i: number) => `${String(i + 1).padStart(2)} ${words[i]!.padEnd(9)}`;
  const row = (from: number) => `   ${[0, 1, 2, 3, 4].map((j) => cell(from + j)).join("  ").trimEnd()}`;
  return `\nYour recovery words, shown once:\n\n${row(0)}\n${row(5)}\n\n${KEEP_THEM}\n\n`;
}

/** An index in [0, n) from crypto.getRandomValues, by rejection, so it is uniform. */
function randomIndex(n: number): number {
  const limit = Math.floor(0x100000000 / n) * n;
  const a = new Uint32Array(1);
  for (;;) {
    crypto.getRandomValues(a);
    if (a[0]! < limit) return a[0]! % n;
  }
}

const TRIES = 3;

/**
 * Show the words once on `tty`, with what to do with them. With `confirm`:
 * wait for "stored", clear the screen, then ask for 2 of the words at random
 * positions. A mismatch shows the words again, up to 3 tries in all, then
 * throws a SecretError (that names no word). Without `confirm` (tests and CI
 * fixtures only), the words are shown and nothing is asked.
 */
export async function showAndConfirmWords(words: readonly string[], tty: Tty, o: { confirm: boolean }): Promise<void> {
  for (let attempt = 1; attempt <= TRIES; attempt++) {
    tty.write(wordsBlock(words));
    if (!o.confirm) return;
    await tty.read("Press Enter once they are stored. ");
    tty.write(CLEAR);
    const a = randomIndex(WORD_COUNT);
    let b = randomIndex(WORD_COUNT - 1);
    if (b >= a) b++;
    tty.write("To check you have them, type two of the words.\n");
    let ok = true;
    for (const i of [a, b].sort((x, y) => x - y)) {
      const answer = (await tty.read(`Word ${i + 1}: `)).trim().toLowerCase();
      if (answer !== words[i]) ok = false;
    }
    if (ok) {
      tty.write("They match.\n\n");
      return;
    }
    if (attempt < TRIES) tty.write("That doesn't match. Here are the words again.\n");
  }
  tty.write(CLEAR);
  throw new SecretError(`the recovery words weren't confirmed after ${TRIES} tries; nothing was written. Run it again for new words`);
}

/**
 * Read the 10 words from `tty`. A word that isn't in the list, or a wrong
 * count, is named (by position, never echoed) and asked again, up to 3 tries.
 */
export async function readRecoveryWords(tty: Tty): Promise<string[]> {
  let last: Error | undefined;
  for (let attempt = 1; attempt <= TRIES; attempt++) {
    try {
      return parseWords(await tty.read("Type your 10 recovery words: "));
    } catch (e) {
      if (!(e instanceof SecretError) || e.message === "cancelled") throw e;
      last = e;
      tty.write(`${e.message}\n`);
    }
  }
  throw last!;
}

/** The identity lines (`AGE-SECRET-KEY-...`) of an identity file's text. */
export function identityLines(text: string): string[] {
  return text
    .split("\n")
    .map((l) => l.trim())
    .filter((l) => l.startsWith("AGE-SECRET-KEY-"));
}

/** The one recipient `age-keygen -y` gives for an identity's text on stdin, checked to be of the right kind. */
async function recipientOf(keygen: SopsRunner, env: Record<string, string>, text: string | Uint8Array): Promise<string> {
  const y = await keygen(["-y"], { env, stdin: text });
  const lines = y.stdout.split("\n").map((l) => l.trim()).filter((l) => l !== "");
  if (y.code !== 0 || lines.length !== 1 || recipientType(lines[0]!) === undefined) {
    const why = scrubToolError(y.stderr);
    throw new SecretError(`age-keygen -y could not read one age public key back (exit ${y.code})${why ? `: ${why}` : ""}`);
  }
  return lines[0]!;
}

/**
 * A new age identity, in memory only: `age-keygen -pq` (or classic), its
 * text (the identity file as age-keygen writes it), the identity line, and its
 * recipient from `age-keygen -y` on stdin. Errors never show the output.
 */
export async function newIdentity(keygen: SopsRunner, env: Record<string, string>, pq: boolean): Promise<{ text: string; identity: string; recipient: string }> {
  const r = await keygen(pq ? ["-pq"] : [], { env });
  if (r.code !== 0) {
    const why = scrubToolError(r.stderr);
    throw new SecretError(`age-keygen could not make a key (exit ${r.code})${why ? `: ${why}` : ""}`);
  }
  const lines = identityLines(r.stdout);
  const prefix = pq ? "AGE-SECRET-KEY-PQ-1" : "AGE-SECRET-KEY-1";
  if (lines.length !== 1 || !lines[0]!.startsWith(prefix)) throw new SecretError(`age-keygen printed something that isn't one ${kindName(pq)} age key (not shown)`);
  const recipient = await recipientOf(keygen, env, r.stdout);
  if (recipientType(recipient) !== (pq ? "pq" : "classic")) throw new SecretError(`age-keygen made a key whose public key isn't ${kindName(pq)}`);
  return { text: r.stdout, identity: lines[0]!, recipient };
}

/** Wrap an identity's text with the words: `age -e -a -j batchpass`, the passphrase on fd 3. Resolves to the armored file. */
export async function wrapIdentity(age: SopsRunner, env: Record<string, string>, identityText: string, words: readonly string[]): Promise<string> {
  const r = await age(["-e", "-a", "-j", "batchpass"], { env: { ...env, AGE_PASSPHRASE_FD: "3" }, stdin: identityText, fd3: passphraseOf(words) });
  if (r.code !== 0 || !r.stdout.startsWith("-----BEGIN AGE ENCRYPTED FILE-----")) {
    const why = scrubToolError(r.stderr);
    throw new SecretError(`age could not wrap the recovery key (exit ${r.code})${why ? `: ${why}` : ""}`);
  }
  return r.stdout;
}

/**
 * Unwrap recovery.age (`wrapped`, its bytes) with the words: `age -d -j
 * batchpass`, the passphrase on fd 3. Resolves to the identity line, after
 * checking with `age-keygen -y` that it is `o.recipient`, the recovery
 * recipient the recipients file records. In memory only.
 */
export async function unwrapIdentity(
  tools: { age: SopsRunner; ageKeygen: SopsRunner },
  env: Record<string, string>,
  wrapped: string | Uint8Array,
  words: readonly string[],
  o: { file: string; recipient: string },
): Promise<string> {
  const r = await tools.age(["-d", "-j", "batchpass"], { env: { ...env, AGE_PASSPHRASE_FD: "3" }, stdin: wrapped, fd3: passphraseOf(words) });
  if (r.code !== 0) {
    if (/incorrect passphrase/.test(r.stderr)) throw new SecretError(`the words don't open ${o.file}: check each word and their order`);
    const why = scrubToolError(r.stderr);
    throw new SecretError(`age could not open ${o.file} (exit ${r.code})${why ? `: ${why}` : ""}`);
  }
  const lines = identityLines(r.stdout);
  if (lines.length !== 1) throw new SecretError(`${o.file} opens, but doesn't hold one age key (not shown)`);
  const recipient = await recipientOf(tools.ageKeygen, env, r.stdout);
  if (recipient !== o.recipient) {
    throw new SecretError(`${o.file} opens, but its key is not the store's recovery recipient (${shortRecipient(o.recipient)}): is it another store's recovery.age?`);
  }
  return lines[0]!;
}
